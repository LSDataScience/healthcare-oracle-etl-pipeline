CREATE OR REPLACE PACKAGE PKG_GERA_MASSA_DADOS AS
    PROCEDURE PRC_POPULAR_ATENDIMENTOS(P_QTD_REGISTROS IN NUMBER DEFAULT 500000);
END PKG_GERA_MASSA_DADOS;
/

CREATE OR REPLACE PACKAGE BODY PKG_GERA_MASSA_DADOS AS
    PROCEDURE PRC_POPULAR_ATENDIMENTOS(P_QTD_REGISTROS IN NUMBER DEFAULT 500000) IS
    BEGIN
        EXECUTE IMMEDIATE 'TRUNCATE TABLE TB_ATENDIMENTO';

        INSERT /*+ APPEND */ INTO TB_ATENDIMENTO (
            CD_ATENDIMENTO, CD_PACIENTE_HASH, CD_UNIDADE, CD_ESPECIALIDADE,
            TP_ATENDIMENTO, CD_CONVENIO, DT_ATENDIMENTO, DT_ALTA,
            TP_ALTA, VL_TOTAL_CONTA, STATUS_CONTA
        )
        WITH BASE AS (
            SELECT
                STANDARD_HASH('PAC_' || TRUNC(DBMS_RANDOM.VALUE(1, 120000)), 'SHA256') AS HASH_PAC,
                TRUNC(DBMS_RANDOM.VALUE(1, 6)) AS UNID,
                TRUNC(DBMS_RANDOM.VALUE(1, 6)) * 10 AS ESP,
                CASE MOD(LEVEL, 10)
                    WHEN 0 THEN 'I' WHEN 1 THEN 'I' WHEN 2 THEN 'I'
                    WHEN 3 THEN 'U' WHEN 4 THEN 'U' WHEN 5 THEN 'U'
                    ELSE 'A'
                END AS TP_AT,
                CASE WHEN MOD(LEVEL, 10) < 7 THEN 1 ELSE TRUNC(DBMS_RANDOM.VALUE(2, 15)) END AS CONV,
                SYSDATE - DBMS_RANDOM.VALUE(1, 730) AS DT_ENT,
                MOD(LEVEL, 25) AS MOD_ABERTO,
                MOD(LEVEL, 50) AS MOD_OBITO,
                MOD(LEVEL, 15) AS MOD_TRANSF,
                ROUND(DBMS_RANDOM.VALUE(150, 45000), 2) AS VL_CONTA,
                MOD(LEVEL, 3) AS MOD_STATUS
            FROM DUAL
            CONNECT BY LEVEL <= P_QTD_REGISTROS
        )
        SELECT
            SEQ_ATENDIMENTO.NEXTVAL, HASH_PAC, UNID, ESP, TP_AT, CONV, DT_ENT,
            CASE WHEN MOD_ABERTO = 0 THEN NULL ELSE DT_ENT + DBMS_RANDOM.VALUE(0.2, 8.5) END,
            CASE
                WHEN MOD_ABERTO = 0 THEN NULL
                WHEN MOD_OBITO = 0 THEN 'OBITO'
                WHEN MOD_TRANSF = 0 THEN 'TRANSFERENCIA'
                ELSE 'MELHORADA'
            END,
            VL_CONTA,
            CASE MOD_STATUS WHEN 0 THEN 'FATURADA' WHEN 1 THEN 'AUDITADA' ELSE 'ABERTA' END
        FROM BASE;

        COMMIT;
        DBMS_STATS.GATHER_TABLE_STATS(USER, 'TB_ATENDIMENTO', CASCADE => TRUE);
    END PRC_POPULAR_ATENDIMENTOS;
END PKG_GERA_MASSA_DADOS;
/

BEGIN
    PKG_GERA_MASSA_DADOS.PRC_POPULAR_ATENDIMENTOS(500000);
END;
/