-- Tabelas simulando um ERP Hospitalar (estilo MV Soul / PEP)
CREATE TABLE TB_UNIDADE (
    CD_UNIDADE      NUMBER(4)     PRIMARY KEY,
    NM_UNIDADE      VARCHAR2(100) NOT NULL,
    TP_UNIDADE      VARCHAR2(30)  NOT NULL, -- 'UTI', 'ENFERMARIA', 'PRONTO_SOCORRO', 'CENTRO_CIRURGICO'
    QT_LEITOS_TOTAL NUMBER(4)     NOT NULL
);

CREATE TABLE TB_ESPECIALIDADE (
    CD_ESPECIALIDADE NUMBER(4)     PRIMARY KEY,
    DS_ESPECIALIDADE VARCHAR2(100) NOT NULL,
    SN_CIRURGICA     CHAR(1)       DEFAULT 'N' CHECK (SN_CIRURGICA IN ('S', 'N'))
);

CREATE TABLE TB_ATENDIMENTO (
    CD_ATENDIMENTO   NUMBER(12)    PRIMARY KEY,
    CD_PACIENTE_HASH VARCHAR2(64)  NOT NULL, -- Dado anonimizado (LGPD)
    CD_UNIDADE       NUMBER(4)     NOT NULL REFERENCES TB_UNIDADE(CD_UNIDADE),
    CD_ESPECIALIDADE NUMBER(4)     NOT NULL REFERENCES TB_ESPECIALIDADE(CD_ESPECIALIDADE),
    TP_ATENDIMENTO   CHAR(1)       NOT NULL CHECK (TP_ATENDIMENTO IN ('I', 'U', 'A')), -- Internação, Urgência, Ambulatório
    CD_CONVENIO      NUMBER(4)     NOT NULL, -- 1 = SUS, >1 = Convênios
    DT_ATENDIMENTO   DATE          NOT NULL,
    DT_ALTA          DATE,
    TP_ALTA          VARCHAR2(20),           -- 'MELHORADA', 'TRANSFERENCIA', 'OBITO', 'EVASAO'
    VL_TOTAL_CONTA   NUMBER(12,2)  DEFAULT 0,
    STATUS_CONTA     VARCHAR2(20)  DEFAULT 'ABERTA'
);

CREATE SEQUENCE SEQ_ATENDIMENTO START WITH 100000 INCREMENT BY 1 CACHE 1000;

