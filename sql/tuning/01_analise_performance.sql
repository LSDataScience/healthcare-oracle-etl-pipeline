-- ETAPA 2: Criando Índice Composto (Covering / Range Scan) e reescrevendo sem TO_CHAR
CREATE INDEX IDX_ATEND_TP_CONV_DT ON TB_ATENDIMENTO (
    TP_ATENDIMENTO,
    CD_CONVENIO,
    DT_ATENDIMENTO,
    CD_UNIDADE,
    CD_ESPECIALIDADE
) INCLUDE (DT_ALTA, VL_TOTAL_CONTA);

EXPLAIN PLAN FOR
WITH ATENDIMENTOS_FILTRADOS AS (
    SELECT /*+ INDEX(A IDX_ATEND_TP_CONV_DT) */
        CD_UNIDADE,
        CD_ESPECIALIDADE,
        DT_ALTA - DT_ATENDIMENTO AS DIAS_PERMANENCIA,
        VL_TOTAL_CONTA
    FROM TB_ATENDIMENTO A
    WHERE A.TP_ATENDIMENTO = 'I'
      AND A.CD_CONVENIO = 1
      AND A.DT_ATENDIMENTO >= DATE '2026-05-01'
      AND A.DT_ATENDIMENTO <  DATE '2026-06-01'
)
SELECT
    U.NM_UNIDADE,
    E.DS_ESPECIALIDADE,
    COUNT(*) AS QTD_INTERNACOES,
    ROUND(AVG(F.DIAS_PERMANENCIA), 2) AS MEDIA_DIAS_PERMANENCIA,
    SUM(F.VL_TOTAL_CONTA) AS FATURAMENTO_TOTAL
FROM ATENDIMENTOS_FILTRADOS F
JOIN TB_UNIDADE U ON U.CD_UNIDADE = F.CD_UNIDADE
JOIN TB_ESPECIALIDADE E ON E.CD_ESPECIALIDADE = F.CD_ESPECIALIDADE
GROUP BY U.NM_UNIDADE, E.DS_ESPECIALIDADE;

