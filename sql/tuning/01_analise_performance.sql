-- ETAPA 1: Query SEM índice (forçando Full Table Scan e função na coluna de data)
EXPLAIN PLAN FOR
SELECT
    U.NM_UNIDADE,
    E.DS_ESPECIALIDADE,
    COUNT(*) AS QTD_INTERNACOES,
    ROUND(AVG(A.DT_ALTA - A.DT_ATENDIMENTO), 2) AS MEDIA_DIAS_PERMANENCIA,
    SUM(A.VL_TOTAL_CONTA) AS FATURAMENTO_TOTAL
FROM TB_ATENDIMENTO A
JOIN TB_UNIDADE U ON U.CD_UNIDADE = A.CD_UNIDADE
JOIN TB_ESPECIALIDADE E ON E.CD_ESPECIALIDADE = A.CD_ESPECIALIDADE
WHERE TO_CHAR(A.DT_ATENDIMENTO, 'YYYY-MM') = '2026-05'
  AND A.TP_ATENDIMENTO = 'I'
  AND A.CD_CONVENIO = 1
GROUP BY U.NM_UNIDADE, E.DS_ESPECIALIDADE;

